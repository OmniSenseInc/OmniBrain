#!/usr/bin/env python3
"""Generate v3 browser bank from canonical JSON; validate before writing."""
import json
import shutil
from pathlib import Path
from assessment_v3 import load_bank
root=Path(__file__).resolve().parent
load_bank(root/'pertanyaan_v3.json')
b=json.loads((root/'pertanyaan_v3.json').read_text())
assert b['version']=='3.0'
actual=[q['id'] for mode in ['screening','discovery'] for q in b[mode] if q['critical']]
assert set(actual)==set(b['critical_ids'])
site=root.parent/'website'/'assets'
(site/'konsultasi-v3-data.js').write_text('/* Generated by consulting/bangun_data_v3.py; edit canonical bank, not this file. */\nwindow.OMNISENSE_CONSULTING_V3 = '+json.dumps(b,ensure_ascii=False,separators=(',',':'))+';\n')
shutil.copy2(root/'konsultasi-v3.js',site/'konsultasi-v3.js')
print('OK generated browser assets from canonical v3 bank')
